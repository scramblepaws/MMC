def fetch(name: str) -> str:
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, name + ".svg")
    if not os.path.exists(path):
        request = urllib.request.Request(
            BASE.format(name), headers={"User-Agent": "MMC/0.1 (icons)"}
        )
        with urllib.request.urlopen(request, timeout=60) as answer:
            data = answer.read()
        with open(path, "wb") as handle:
            handle.write(data)
    with open(path, "r", encoding="utf-8") as handle:
        return handle.read()


def shapes_of(svg: str):
    """The shapes of one icon, in the order they are drawn."""
    root = ET.fromstring(svg)
    out = []
    for element in root:
        tag = element.tag.split("}")[-1]
        if tag == "path":
            out.append(("Path", element.get("d", "")))
        elif tag == "polyline":
            out.append(("Polyline", element.get("points", "")))
        elif tag == "polygon":
            out.append(("Polygon", element.get("points", "")))
        elif tag == "line":
            out.append(
                (
                    "Line",
                    "{} {} {} {}".format(
                        element.get("x1", 0),
                        element.get("y1", 0),
                        element.get("x2", 0),
                        element.get("y2", 0),
                    ),
                )
            )
        elif tag == "circle":
            out.append(
                (
                    "Circle",
                    "{} {} {}".format(
                        element.get("cx", 0),
                        element.get("cy", 0),
                        element.get("r", 0),
                    ),
                )
            )
        elif tag == "rect":
            out.append(
                (
                    "Rect",
                    "{} {} {} {}".format(
                        element.get("x", 0),
                        element.get("y", 0),
                        element.get("width", 0),
                        element.get("height", 0),
                    ),
                )
            )
    return out


def main() -> None:
    entries = []
    for name, lucide in ICONS.items():
        try:
            svg = fetch(lucide)
        except Exception as error:  # noqa: BLE001
            print("skipping", name, error)
            continue
        entries.append((name, shapes_of(svg)))

    with open(OUT, "w", encoding="utf-8", newline="\n") as out:
        out.write("// Generated by tools/gen_icons.py, do not edit by hand.\n")
        out.write("// The icons are the outline icons of Lucide, ISC licensed,\n")
        out.write("// https://github.com/lucide-icons/lucide\n\n")
        out.write('#include "ui/IconData.h"\n\n')
        out.write("namespace mmc {\nnamespace {\n\n")
        for name, shapes in entries:
            out.write("const IconShapeData k%s[] = {\n" % name.replace("-", "_").capitalize())
            for kind, data in shapes:
                data = " ".join(data.split())
                out.write('    { IconShape::%s, "%s" },\n' % (kind, data))
            out.write("};\n\n")
        out.write("} // namespace\n\nconst IconData kIcons[] = {\n")
        for name, shapes in entries:
            out.write(
                '    { "%s", k%s, %d },\n'
                % (name, name.replace("-", "_").capitalize(), len(shapes))
            )
        out.write("};\n\n")
        out.write("const int kIconCount = %d;\n\n" % len(entries))
        out.write("} // namespace mmc\n")

    print("wrote", OUT, "with", len(entries), "icons")


if __name__ == "__main__":
    main()
